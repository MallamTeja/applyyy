-- WHY THIS MIGRATION EXISTS (2026-11-01).
--
-- Teja asked for the review page's AI box to be a CHAT: past chats, and a memory of earlier
-- messages within the same chat. The edge function `resume-assist` stays stateless (it never
-- writes); the browser stores each finished exchange here, and sends the last few messages of
-- the active chat back as context on the next ask.
--
-- One row per message. A "chat" is every row sharing a chat_id under one application, so no
-- second table is needed: a chat's title is its first user message, its order is created_at.
--
-- APPEND-ONLY, like application_events: a chat is a record of what was asked and proposed, and
-- what was APPLIED is derived from the resume itself (the page compares each proposed op with
-- the current text), so no row ever needs updating. Forbidding update/delete keeps it honest.
--
-- Not re-runnable as written (bare create table / create policy): run once.

create table public.resume_chat_messages (
  -- bigint identity: always read in time order, like application_events.
  id bigint generated always as identity primary key,
  -- The owner; RLS compares it with the caller.
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  -- The resume this chat is about. Cascade: a chat dies with its application.
  application_id uuid not null references public.applications (id) on delete cascade,
  -- Groups messages into one chat; generated by the browser when a chat starts.
  chat_id uuid not null,
  -- Who said it. A closed set: anything else is not a chat message.
  role text not null check (role in ('user', 'assistant')),
  -- The operator's instruction, or the AI's one-line note. Bounded: it is resent as context.
  content text not null check (char_length(content) between 1 and 2000),
  -- Assistant only: the proposed edits, as the page stored them (targets resolved to refs).
  ops jsonb check (ops is null or jsonb_typeof(ops) = 'array'),
  -- Assistant only: what the ask cost in tokens.
  usage jsonb check (usage is null or jsonb_typeof(usage) = 'object'),
  -- Server time, so ordering never depends on a browser clock.
  created_at timestamptz not null default now(),
  -- A user message never carries ops; an assistant message always does (possibly an empty list).
  constraint resume_chat_messages_ops_by_role check ((role = 'assistant') = (ops is not null))
);

-- RLS on, and forced so even the table owner goes through the policies below.
alter table public.resume_chat_messages enable row level security;
-- Forced: no role reads around the policies by owning the table.
alter table public.resume_chat_messages force row level security;

-- APPEND-ONLY: the same trigger function application_events uses; it raises for every role,
-- the service-role key included.
create trigger forbid_update
  before update on public.resume_chat_messages
  for each row execute function applyy_internal.forbid_mutation();

-- And deletes, so history cannot be quietly trimmed either.
create trigger forbid_delete
  before delete on public.resume_chat_messages
  for each row execute function applyy_internal.forbid_mutation();

-- The only read: one application's chats, in time order.
create index resume_chat_messages_application_created_idx
  on public.resume_chat_messages (application_id, created_at);

-- No anonymous access at all; the signed-in user may only read and append.
revoke all on public.resume_chat_messages from anon;
-- Exactly the two verbs the page uses; no update or delete grant exists to misuse.
grant select, insert on public.resume_chat_messages to authenticated;

-- Read your own messages only.
create policy "read own chat messages" on public.resume_chat_messages
  for select to authenticated
  using ((select auth.uid()) = user_id);

-- Append your own messages, and only about an application you own: the foreign key alone would
-- accept another tenant's application id, because FK checks bypass RLS.
create policy "append own chat messages" on public.resume_chat_messages
  for insert to authenticated
  with check (
    (select auth.uid()) = user_id
    and exists (
      select 1 from public.applications a
      where a.id = application_id and a.user_id = (select auth.uid())
    )
  );

-- Shown in the Supabase dashboard, so the rule travels with the table.
comment on table public.resume_chat_messages is
  'Review-page AI chat (2026-11-01). Append-only: UPDATE and DELETE raise. Applied state is derived from the resume, never stored.';
