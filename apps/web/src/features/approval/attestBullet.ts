/* Attesting a NEW bullet the master does not have, from the approval page or the AI chat (R0', 2026-11-01).
 *
 * WHY THE MASTER FIRST - the same reason as attestSkill.ts, which this mirrors. The page promises
 * every line traces to master version N, and the auditor traces each bullet by ref to the PINNED
 * master under its parent. So typing a new line under "Aczen Technologies" is the operator vouching
 * for that claim: it lands in the master as a new immutable version, under that entry, and only then
 * on this resume (by ref, via addMasterBullet), with the row re-pinned to that version. Writing the
 * text only into the tailored copy would be an untraced claim wearing the "verified" colour.
 *
 * ORDER: master insert, then one application UPDATE. Everything that can be proven without a write
 * is proven first (plan below), so a refusal there writes nothing anywhere. A landed insert followed
 * by a refused row write leaves a new master version holding a bullet the operator vouched for, and
 * the row unchanged; full atomicity would need a database function. */

// Types only: the resume and master shapes from the app's single contract seam.
import type { MasterProfile, ResolvedResume } from '../../data/contract';
// The newest stored master, and the insert-only version writer; reused, never re-implemented.
import { loadCurrentMasterProfile, storeMasterProfile, storeRefusalMessage } from '../settings/masterStore';
// The ingest gate: fills the nullable keys the table's check constraint demands, and refuses a
// malformed or duplicate-id profile before it can become a version.
import { checkMasterProfile } from '../settings/masterIngest';
// The pure edits: the master shape check, the rebuild, FULL, the add-back, and the R0' gate itself.
import {
  // Structural equality that ignores jsonb key order.
  deepEqual,
  // The cap an edited bullet is held to; a new one gets the same.
  MAX_EDIT_LENGTH,
  // The shape gate the page applies to every master row.
  masterFromRow,
  // The tailor's resume, rebuilt by the validator at a given version.
  rebuildOriginal,
  // The whole master as the validator resolves it.
  resolveFullMaster,
  // A master bullet onto the resume by ref, copied whole from FULL.
  addMasterBullet,
  // The save boundary's own rule, run here before any write.
  tracesToMaster,
  // The five bullet-bearing sections, for the runtime guard on args.section.
  DIFF_BULLET_SECTIONS,
  // The section union, so a typo in a section name fails typecheck.
  type BulletSection,
} from './tailoredEdits';
// The write boundary every resume edit goes through, able to move the pin with the resume.
import { saveTailoredEdit, type EditSource, type StoredRow } from './saveTailoredEdit';

/* The client the two masterStore calls take; the page's real client, or a test double cast to it.
   Derived from masterStore's own signature so the two can never drift apart. */
type Client = Parameters<typeof loadCurrentMasterProfile>[0];

/* Everything one attest needs from the page. */
export interface AttestBulletArgs {
  // The row being reviewed.
  readonly applicationId: string;
  // The section of the entry the new line goes under.
  readonly section: BulletSection;
  // The master id of that entry (the resume entry's ref); the new bullet's parent.
  readonly parentRef: string;
  // The operator's wording; it becomes the master bullet's text, verbatim after trimming.
  readonly text: string;
  // The resume as stored now (may carry the operator's earlier edits).
  readonly current: ResolvedResume;
  // The tailor's version at the CURRENT pin, rebuilt from tailor_refs.
  readonly original: ResolvedResume;
  // applications.tailor_refs as loaded; untyped JSON from the row.
  readonly tailorRefs: unknown;
  // The stamp the page loaded the row at; the row write is conditional on it.
  readonly expectedUpdatedAt: string;
  // A fresh id for the new master bullet; generated by the caller so tests can name it.
  readonly newBulletId: string;
  // Who decided the new bullet (a hand click, or the AI chat card), for the history note; required so no caller defaults it.
  readonly source: EditSource;
}

/* How an attest ends. On success the page gets the new pin's master and original, which it must
   swap in before redrawing, or the next edit would be checked against the old version. */
export type AttestBulletOutcome =
  | {
      // The discriminator the page branches on.
      readonly ok: true;
      // The saved resume, at the new pin.
      readonly resume: ResolvedResume;
      // The master at the new pin.
      readonly master: MasterProfile;
      // The tailor's version rebuilt at the new pin (identical claims, new version label).
      readonly original: ResolvedResume;
      // tailor_refs as written, carrying the new pin.
      readonly tailorRefs: unknown;
      // The new master bullet now on the resume, for Undo (remove).
      readonly bulletRef: string;
      // The row's new stamp.
      readonly updatedAt: string;
      // Whether the history note landed.
      readonly eventRecorded: boolean;
    }
  | {
      // The discriminator the page branches on.
      readonly ok: false;
      // Said for a person; the page shows it verbatim.
      readonly message: string;
      // True only when a master version was created before the row write failed.
      readonly masterInserted: boolean;
      // What the row holds now, when a refused row write re-read it.
      readonly stored?: StoredRow;
    };

/* What plan() proves: the relabelled tailor_refs, the original at the target pin, and the resume to write. */
type Plan =
  // Proven: everything the write needs.
  | { readonly ok: true; readonly refs: unknown; readonly original: ResolvedResume; readonly resume: ResolvedResume }
  // Not provable: the sentence to show, and nothing has been written because of it.
  | { readonly ok: false; readonly message: string };

// One refusal sentence for "the newer master would change this resume", used before and after insert.
const CHANGED_MASTER =
  // Names the safe alternative, so a refusal is never a dead end.
  'your master profile changed since this resume was tailored, so adding a line here would also change other lines. Add it on the Master Profile page instead.';

/* THE PROOF THAT MAKES THE RE-PIN AND THE ADD HONEST, all pure, run before the master insert and
 * again at the version the database actually assigned:
 *   1. the tailor's claims rebuild at the target version to EXACTLY what they were (as attestSkill);
 *   2. every skill on the resume still resolves to the same name and group (as attestSkill: the
 *      gate's skills rule accepts an unchanged list without consulting the master);
 *   3. the new bullet goes on by ref from FULL at the target (addMasterBullet), so its words are the
 *      master's own;
 *   4. the resulting resume passes tracesToMaster against the target, so every entry and bullet
 *      already printed - including ones added back earlier, which (1) does not cover - is still the
 *      target master's, field for field. */
function plan(target: MasterProfile, version: number, args: AttestBulletArgs): Plan {
  // tailor_refs must be an object to carry a pin at all.
  if (typeof args.tailorRefs !== 'object' || args.tailorRefs === null) return { ok: false, message: CHANGED_MASTER };
  // The tailor's record, relabelled to the target version and nothing else.
  const refs = { ...(args.tailorRefs as Record<string, unknown>), master_version: version };
  // (1) The validator's own rebuild; null means the target master no longer supports this tailoring.
  const original = rebuildOriginal(refs, target, version);
  // Same claims as at the current pin, apart from the version label.
  if (original === null || !deepEqual(original, { ...args.original, master_version: version })) return { ok: false, message: CHANGED_MASTER };
  // (2) The target's skills by id.
  const skillsById = new Map(target.skills.map((skill) => [skill.id, skill]));
  // Every printed skill must exist there, spelled and grouped the same.
  const skillsHold = args.current.skills.every((skill) => {
    // The node this ref points at in the target master.
    const node = skillsById.get(skill.ref);
    // Missing or respelled would change what the resume prints.
    return node !== undefined && node.name === skill.name && node.category === skill.category;
  });
  // A changed skill is a changed line: refuse the re-pin.
  if (!skillsHold) return { ok: false, message: CHANGED_MASTER };
  // (3) FULL at the target, which holds the new bullet under its parent.
  const full = resolveFullMaster(target, version);
  // No FULL means nothing can be traced at that version.
  if (full === null) return { ok: false, message: CHANGED_MASTER };
  // The stored resume relabelled to the target pin: the only difference a re-pin may add.
  const atPin = { ...args.current, master_version: version };
  // The new bullet onto the re-pinned resume by ref, inserted where the master puts it.
  const added = addMasterBullet(atPin, full, args.newBulletId);
  // e.g. the parent entry is not printed; said in addMasterBullet's own words.
  if (!added.ok) return { ok: false, message: added.reason };
  // (4) The save boundary's rule, run here first so a refusal never leaves a stray master version.
  if (!tracesToMaster(atPin, added.resume, original, target)) return { ok: false, message: CHANGED_MASTER };
  // Proven: everything the write needs.
  return { ok: true, refs, original, resume: added.resume };
}

/* One click: the bullet into the master as a new version, then onto this resume, re-pinned. Never
   throws: every path ends in an AttestBulletOutcome, like attestSkill and saveTailoredEdit. */
export async function attestBullet(client: Client, args: AttestBulletArgs): Promise<AttestBulletOutcome> {
  /* Runtime guards before anything is read: the type says string and a bullet section, but the AI
     chat builds these args from model output, and this function promises never to throw (review
     finding, 2026-11-01). */
  if (typeof args.text !== 'string') return { ok: false, message: 'a new line needs some text.', masterInserted: false };
  // Only the five bullet-bearing sections hold bullets; 'skills' or 'summary' would throw below.
  if (!(DIFF_BULLET_SECTIONS as readonly string[]).includes(args.section)) return { ok: false, message: 'that section does not hold bullets.', masterInserted: false };
  // The printed words: the operator's text, trimmed (surrounding whitespace is never content).
  const text = args.text.trim();
  // Blank would store an empty claim in the master.
  if (text === '') return { ok: false, message: 'a new line needs some text.', masterInserted: false };
  // The same cap an edited bullet has; over it is a paste accident, refused rather than truncated.
  if (text.length > MAX_EDIT_LENGTH) return { ok: false, message: `the text is longer than ${MAX_EDIT_LENGTH} characters.`, masterInserted: false };
  // The entries this section prints now, read defensively (a legacy row may lack the key).
  const printed = args.current[args.section] as readonly { readonly ref: string }[] | undefined;
  // The parent must be on the resume, or the new line would be added to the master and then refused here.
  if (!Array.isArray(printed) || !printed.some((entry) => entry.ref === args.parentRef)) {
    // Refused before any read or write.
    return { ok: false, message: 'the entry this line belongs to is not on this resume. Add the entry first.', masterInserted: false };
  }

  // The NEWEST master, not the pinned one: versions are immutable, so the new one builds on the latest.
  const latest = await loadCurrentMasterProfile(client);
  // No master, or no answer: nothing can be attested against.
  if (latest.kind !== 'loaded') {
    // A read failure keeps the database's words; an empty table says so plainly.
    const why = latest.kind === 'failed' ? `could not read your master profile: ${latest.message}` : 'no master profile is stored.';
    // Nothing was written, so nothing needs undoing.
    return { ok: false, message: why, masterInserted: false };
  }
  // The same shape gate the page applies to every master it diffs against.
  const latestMaster = masterFromRow(latest.profile);
  // A malformed latest master cannot be the base of a new version.
  if (latestMaster === null) return { ok: false, message: 'your latest master profile is malformed, so nothing was added.', masterInserted: false };
  // The parent's section in the latest master, typed as the shape every bullet-bearing node shares.
  const nodes = latestMaster[args.section] as readonly { readonly id: string; readonly bullets: readonly unknown[] }[];
  // The parent must still exist there; a deleted entry cannot take a new line.
  if (!nodes.some((node) => node.id === args.parentRef)) {
    // Named, so the operator knows the master moved on rather than that the click failed.
    return { ok: false, message: 'that entry is no longer in your latest master profile, so nothing was added.', masterInserted: false };
  }
  // The section with the new bullet appended last under its parent: master order is meaningful and
  // every existing ref stays valid. tags [] because a hand-vouched line has no tailoring tags yet.
  const withBullet = nodes.map((node) => (node.id === args.parentRef ? { ...node, bullets: [...node.bullets, { id: args.newBulletId, text, tags: [] }] } : node));
  // The ingest gate fills explicit nulls and refuses duplicate ids or a malformed profile.
  const checked = checkMasterProfile({ ...latestMaster, [args.section]: withBullet });
  // A profile that fails ingest must never become a version.
  if (!checked.ok) return { ok: false, message: 'the master profile with this line did not pass validation, so nothing was added.', masterInserted: false };
  // The ingest output, with the explicit nulls the table's check constraint requires.
  const target = checked.profile;

  /* PROVE BEFORE WRITING, at the version the insert should get (latest + 1); the proof does not
     depend on the number beyond the label it stamps. */
  const planned = plan(target, latest.version + 1, args);
  // Refused before any write: neither a master version nor a row change.
  if (!planned.ok) return { ok: false, message: planned.message, masterInserted: false };

  // Insert-only; the database assigns the version and the content hash.
  const stored = await storeMasterProfile(client, target);
  // Each refusal named: nothing has been written anywhere yet.
  // Worded by masterStore, which owns StoreOutcome: this file kept a copy until 2026-11-01, and two
  // copies of one sentence drift apart the first time only one is edited.
  if (stored.kind !== 'stored') return { ok: false, message: `could not add it to your master profile: ${storeRefusalMessage(stored)}.`, masterInserted: false };
  // The real number, which a concurrent save could have pushed past latest+1.
  const version = stored.version;

  // The proof again at the real version (pure; only the label differs from the planned one).
  const proven = plan(target, version, args);
  // Refused after the insert: the version stays (immutable), the row is untouched.
  if (!proven.ok) return { ok: false, message: proven.message, masterInserted: true };

  // One write: the resume with the new line, and all three pins, guarded by status and stamp.
  const saved = await saveTailoredEdit(client, {
    // The row being written.
    applicationId: args.applicationId,
    // The resume with the attested bullet, already labelled with the new version.
    resume: proven.resume,
    // What is stored now, for the R0' check (relabelled to the new pin inside the save).
    previous: args.current,
    // The tailor's version at the NEW pin, proven claim-for-claim identical above.
    original: proven.original,
    // The new pin's master, the source FULL and the new bullet come from.
    master: target,
    // Optimistic concurrency: refused if another tab changed the row.
    expectedUpdatedAt: args.expectedUpdatedAt,
    // The event names the new master bullet and the words the operator vouched for.
    event: { kind: 'resume_attest_bullet', ref: args.newBulletId, before: null, after: text, source: args.source },
    // All three pins move in this same statement.
    repin: { version, tailorRefs: proven.refs },
  });
  // Refused or unknown: the page shows what is stored; the master version stays.
  if (!saved.ok) return { ok: false, message: saved.message, masterInserted: true, ...(saved.stored ? { stored: saved.stored } : {}) };
  // Everything the page needs to redraw against the new pin.
  return {
    // Landed.
    ok: true,
    // The resume as stored.
    resume: proven.resume,
    // The pin's master, which the page swaps into the row's source.
    master: target,
    // The pin's original, so "edited" keeps being derived correctly.
    original: proven.original,
    // The tailor's record as stored, for any later re-pin.
    tailorRefs: proven.refs,
    // The new bullet, for Undo.
    bulletRef: args.newBulletId,
    // The stamp the next edit must present.
    updatedAt: saved.updatedAt,
    // So the page can say when only the history note is missing.
    eventRecorded: saved.eventRecorded,
  };
}
