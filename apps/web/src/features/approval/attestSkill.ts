/* Attesting a skill the master does not have, from the approval page's ✗ chip.
 *
 * WHY THE MASTER FIRST. The page promises every line traces to master version N, and the auditor
 * checks tailored skills by id against the PINNED master. So a click on ✗ Java is the operator
 * vouching for Java: it lands in the master as a new immutable version, and only then on this
 * resume, with the row re-pinned to that version. Writing it only into the tailored copy would be
 * an untraced claim wearing the "verified" colour.
 *
 * ORDER: master insert, then one application UPDATE. A refused insert writes nothing to the row.
 * A landed insert followed by a refused row write leaves a new master version holding a skill the
 * operator vouched for, and the row unchanged; full atomicity would need a database function. */

// Types only: the resume and master shapes from the app's single contract seam.
import type { MasterProfile, ResolvedResume } from '../../data/contract';
// The newest stored master, the insert-only version writer and its refusal wording; reused, never re-implemented.
import { loadCurrentMasterProfile, storeMasterProfile, storeRefusalMessage } from '../settings/masterStore';
// The ingest gate: fills the nullable keys the table's check constraint demands, and refuses a
// malformed or duplicate-id profile before it can become a version.
import { checkMasterProfile } from '../settings/masterIngest';
// The Master page's own name match (bf's e136e52), so both add paths refuse the same duplicates.
import { masterSkillNamed } from '../settings/masterAdd';
// The pure edits: the shape check, the rebuild from tailor_refs, the existing add/match rules.
import { addableSkillFor, addSkill, deepEqual, masterFromRow, rebuildOriginal, skillGroupWrapReason, skillTokens } from './tailoredEdits';
// The write boundary every resume edit goes through, now able to move the pin with the resume.
import { saveTailoredEdit, type EditSource, type StoredRow } from './saveTailoredEdit';
// The one-page rule, live: the attested resume is fitted on one page before it is saved (2026-11-07).
import { fitEditToOnePage } from './pageFitEdit';

/* The client the two masterStore calls take; the page's real client, or a test double cast to it.
   Derived from masterStore's own signature so the two can never drift apart. */
type Client = Parameters<typeof loadCurrentMasterProfile>[0];

/* Everything one attest needs from the page. */
export interface AttestArgs {
  // The row being reviewed.
  readonly applicationId: string;
  // The missing JD keyword exactly as the chip shows it; it becomes the skill's printed name.
  readonly keyword: string;
  // The resume group it prints under, chosen by the operator from the master's own categories.
  readonly category: string;
  // The resume as stored now (may carry the operator's earlier edits).
  readonly current: ResolvedResume;
  // The tailor's version at the CURRENT pin, rebuilt from tailor_refs.
  readonly original: ResolvedResume;
  // applications.tailor_refs as loaded; untyped JSON from the row.
  readonly tailorRefs: unknown;
  // The stamp the page loaded the row at; the row write is conditional on it.
  readonly expectedUpdatedAt: string;
  // A fresh id for the new master skill; generated by the caller so tests can name it.
  readonly newSkillId: string;
  // Who decided the attest (a hand click, or the AI chat), for the history note; required so no caller defaults it.
  readonly source: EditSource;
  /* The PINNED master: the version this row was tailored from (2026-11-12). A skill it already holds is added
     at the pin, with no master write and no re-pin. Required, so no caller falls back to the latest by omission. */
  readonly pinnedMaster: MasterProfile;
  /* The row's JD keywords (selected_jd_keywords), for the one-page fit this save runs (2026-11-07).
     Required, so no caller can skip the fit by omission. */
  readonly jdKeywords: readonly string[];
  /* One line per skill group (2026-11-12): 'refuse' an add that would wrap its group, or 'allow' it with a
     notice when the owner said "all". Required, so no caller can skip the rule by omission. */
  readonly wrap: 'refuse' | 'allow';
}

/* How an attest ends. On success the page gets the new pin's master and original, which it must
   swap in before redrawing, or the next edit would be checked against the old version. */
export type AttestOutcome =
  | {
      // The discriminator the page branches on.
      readonly ok: true;
      // The saved resume, at the new pin.
      readonly resume: ResolvedResume;
      // What the one-page fit cut in this save, in words for the page; null when nothing was cut.
      readonly notice: string | null;
      // The master at the new pin.
      readonly master: MasterProfile;
      // The tailor's version rebuilt at the new pin (identical claims, new version label).
      readonly original: ResolvedResume;
      // tailor_refs as written, carrying the new pin.
      readonly tailorRefs: unknown;
      // The master skill now on the resume, for Undo (remove_skill).
      readonly skillRef: string;
      // The row's new stamp.
      readonly updatedAt: string;
      // Whether this save wrote a new MASTER version; false at the pin (2026-11-12), so the page never says it did.
      readonly masterInserted: boolean;
      // Whether the history note landed.
      readonly eventRecorded: boolean;
    }
  | {
      // The discriminator the page branches on.
      readonly ok: false;
      // Said for a person; the page shows it verbatim.
      readonly message: string;
      // True only when a master version was created before the row write failed.
      readonly masterInserted: boolean;
      // What the row holds now, when a refused row write re-read it.
      readonly stored?: StoredRow;
    };

/* The proof that makes a re-pin honest: at the target version, the tailor's claims rebuild to
   EXACTLY what they were, and every skill already on the resume resolves to the same name and
   group. Anything else means the newer master would silently change a line of this resume. */
function rebuildAt(target: MasterProfile, version: number, args: AttestArgs): { refs: unknown; original: ResolvedResume } | null {
  // tailor_refs must be an object to carry a pin at all.
  if (typeof args.tailorRefs !== 'object' || args.tailorRefs === null) return null;
  // The tailor's record, relabelled to the target version and nothing else.
  const refs = { ...(args.tailorRefs as Record<string, unknown>), master_version: version };
  // The validator's own rebuild; null means the target master no longer supports this tailoring.
  const original = rebuildOriginal(refs, target, version);
  // No rebuild, no proof: refuse rather than re-pin onto a master the tailoring does not fit.
  if (original === null) return null;
  // Same claims as at the current pin, apart from the version label.
  if (!deepEqual(original, { ...args.original, master_version: version })) return null;
  // Skills the operator added earlier must still exist, spelled and grouped the same.
  const byId = new Map(target.skills.map((skill) => [skill.id, skill]));
  // Every printed skill, checked against the target master node.
  const skillsHold = args.current.skills.every((skill) => {
    // The node this ref points at in the target master.
    const node = byId.get(skill.ref);
    // Missing or respelled would change what the resume prints.
    return node !== undefined && node.name === skill.name && node.category === skill.category;
  });
  // The proof holds only when both checks pass; the caller needs the relabelled refs and original.
  return skillsHold ? { refs, original } : null;
}

// One refusal sentence for "the newer master would change this resume", used before and after insert.
const CHANGED_MASTER =
  // Names the safe alternative, so a refusal is never a dead end.
  'your master profile changed since this resume was tailored, so adding a skill here would also change other lines. Add it on the Master Profile page instead.';

/* Add a skill the row's PINNED master already holds (2026-11-12): no master write, no re-pin, so the tailor's
   original, the pin and every other line stay exactly as they are. The same one-line and one-page rules as the
   attest below; the event is resume_add_skill, because nothing was vouched into the master and the pin did not move. */
async function addAtPin(client: Client, args: AttestArgs, skillRef: string): Promise<AttestOutcome> {
  // The pinned master node, for the one-line check in the spelling and group that will print.
  const node = args.pinnedMaster.skills.find((skill) => skill.id === skillRef);
  // Defensive: the caller found it in this master, so this only guards a future caller.
  if (node === undefined) return { ok: false, message: 'That skill is not in your master profile, so it cannot be added.', masterInserted: false };
  // One line per group (c01372e), judged before any write.
  const wraps = skillGroupWrapReason(args.current, node.name, node.category);
  // Would wrap and the owner did not say "all": nothing written.
  if (wraps !== null && args.wrap !== 'allow') return { ok: false, message: wraps, masterInserted: false };
  // The pure add at the pin; it refuses a skill already printed, in its own words.
  const added = addSkill(args.current, args.pinnedMaster, skillRef, 'allow');
  // Refused: nothing written.
  if (!added.ok) return { ok: false, message: added.reason, masterInserted: false };
  // One page, against the pinned master, exactly as every other edit at the pin.
  const fitted = fitEditToOnePage(added.resume, args.jdKeywords, { previous: args.current, master: args.pinnedMaster });
  // Refused before the write, in the check's own words.
  if (!fitted.ok) return { ok: false, message: fitted.reason, masterInserted: false };
  // One write of tailored_profile only: no repin, so master_version and tailor_refs are untouched.
  const saved = await saveTailoredEdit(client, {
    // The row being written.
    applicationId: args.applicationId,
    // The resume with the one skill added, fitted on one page.
    resume: fitted.resume,
    // What is stored now, for the R0 check.
    previous: args.current,
    // The tailor's version at the same pin.
    original: args.original,
    // The pinned master, the only source the skill comes from.
    master: args.pinnedMaster,
    // Optimistic concurrency, as every edit.
    expectedUpdatedAt: args.expectedUpdatedAt,
    // An add of an existing master skill: the pin did not move.
    event: { kind: 'resume_add_skill', ref: skillRef, before: null, after: node.name, source: args.source, pageFitTrimmed: fitted.trimmed },
  });
  // Refused or unknown: the page shows what is stored.
  if (!saved.ok) return { ok: false, message: saved.message, masterInserted: false, ...(saved.stored ? { stored: saved.stored } : {}) };
  // The page swaps in the SAME pin's master, original and refs, so its source does not change.
  return {
    // Landed.
    ok: true,
    // As stored.
    resume: fitted.resume,
    // The trim and an allowed wrap, in words; null when neither happened.
    notice: [fitted.notice, wraps === null ? null : `"${node.category}" now wraps onto a second line, because you said "all".`].filter((line): line is string => line !== null).join(' ') || null,
    // Unchanged pin.
    master: args.pinnedMaster,
    // Unchanged original.
    original: args.original,
    // Unchanged tailor record.
    tailorRefs: args.tailorRefs,
    // For Undo.
    skillRef,
    // The next edit's stamp.
    updatedAt: saved.updatedAt,
    // Nothing was written to the master on this path.
    masterInserted: false,
    // Whether the history note landed.
    eventRecorded: saved.eventRecorded,
  };
}

export async function attestSkill(client: Client, args: AttestArgs): Promise<AttestOutcome> {
  // The printed name: the keyword as shown, trimmed.
  const name = args.keyword.trim();
  // The group it prints under.
  const category = args.category.trim();
  // Blank would store a nameless skill, or a group the renderer prints as an empty heading.
  if (name === '' || category === '') return { ok: false, message: 'a skill needs a name and a group.', masterInserted: false };

  // The NEWEST master, not the pinned one: versions are immutable, so the new one builds on the latest.
  const latest = await loadCurrentMasterProfile(client);
  // No master, or no answer: nothing can be attested against.
  if (latest.kind !== 'loaded') {
    // A read failure keeps the database's words; an empty table says so plainly.
    const why = latest.kind === 'failed' ? `could not read your master profile: ${latest.message}` : 'no master profile is stored.';
    // Nothing was written, so nothing needs undoing.
    return { ok: false, message: why, masterInserted: false };
  }
  // The same shape gate the page applies to every master it diffs against.
  const latestMaster = masterFromRow(latest.profile);
  // A malformed latest master cannot be the base of a new version.
  if (latestMaster === null) return { ok: false, message: 'your latest master profile is malformed, so nothing was added.', masterInserted: false };

  /* Already printed under any spelling of the same skill: refused BEFORE any master write (2026-11-04).
     addableSkillFor below skips skills already on the resume, so a second attest of a printed skill
     found no master node and inserted a duplicate: live 2026-11-01, "Testing" attested twice 9 s
     apart became two master skills and the two printed "Testing"s Teja then asked the AI to remove. */
  if (args.current.skills.some((skill) => skillTokens(skill.name) === skillTokens(name))) {
    // Nothing written; said in the operator's own word.
    return { ok: false, message: `"${name}" is already on this resume.`, masterInserted: false };
  }
  /* OLDER ROWS (Teja blocked 2026-11-12 16:53, DXC row): the latest master moved on (v45 and v47 dropped skills)
     after most queue rows were tailored, so re-pinning to it changed other lines and every add was refused with
     CHANGED_MASTER. A skill the PINNED master already holds needs neither: it is added at the pin, so only that
     skill changes. The tailor's match rule first, then the Master page's name match ("fastapi" -> "FastAPI"). */
  const atPin = addableSkillFor(name, args.current, args.pinnedMaster) ?? masterSkillNamed(args.pinnedMaster, name);
  // Held by the pin: the add needs no master version, whatever the latest says.
  if (atPin !== undefined && atPin !== null) return addAtPin(client, args, 'ref' in atPin ? atPin.ref : atPin.id);
  /* Another row may already have attested this skill: reuse that master skill by its id rather than
     inserting a duplicate version. Same matching rule the existing "＋ Add" offer uses. */
  const existing = addableSkillFor(name, args.current, latestMaster);
  /* Not addable, yet the master already holds the name (2026-11-05, with bf's e136e52): appending it
     would store a duplicate master version (live v11/v14 held a second and third "Testing"). Refused
     with the master's own spelling and group; nothing is written. */
  const held = existing === null ? masterSkillNamed(latestMaster, name) : undefined;
  // Already in the master under this name (any case): say where, add nothing.
  if (held !== undefined) {
    // No insert ran, so masterInserted is false.
    return { ok: false, message: `"${name}" is already in your master profile as "${held.name}" (${held.category}); nothing was added.`, masterInserted: false };
  }
  /* ONE LINE PER GROUP (2026-11-12), checked BEFORE any write: refused after the master insert, the new
     version would stay behind (versions are immutable). Asked with what will print: the master's own
     spelling and group when it already holds the skill, else the vouched name under the picked group. */
  const wraps = skillGroupWrapReason(args.current, existing?.name ?? name, existing?.category ?? category);
  // Would wrap and the owner did not say "all": nothing written, the full group named.
  // `!== 'allow'`, not `=== 'refuse'`: a caller that sends no value (an untyped test double) fails CLOSED.
  if (wraps !== null && args.wrap !== 'allow') return { ok: false, message: wraps, masterInserted: false };
  // Allowed past the line: said after the save, so the wrap is never silent.
  const wrapNotice = wraps === null ? null : `"${existing?.category ?? category}" now wraps onto a second line, because you said "all".`;
  // The master skill that will go on the resume.
  const skillRef = existing?.ref ?? args.newSkillId;
  // The master the row will be pinned to, before the database assigns a version.
  let target: MasterProfile;
  // Already in the latest master: pin to it as it is.
  if (existing !== null) target = latestMaster;
  else {
    // Appended last: document order is meaningful and every existing ref stays valid.
    const withSkill = { ...latestMaster, skills: [...latestMaster.skills, { id: args.newSkillId, name, category }] };
    // The ingest gate fills explicit nulls and refuses duplicate ids or a malformed profile.
    const checked = checkMasterProfile(withSkill);
    // A profile that fails ingest must never become a version.
    if (!checked.ok) return { ok: false, message: 'the master profile with this skill did not pass validation, so nothing was added.', masterInserted: false };
    // The ingest output, with the explicit nulls the table's check constraint requires.
    target = checked.profile;
  }

  /* PROVE BEFORE WRITING. The version the row would get is latest+1 for a new version, else the
     latest itself; the proof does not depend on the number beyond the label it stamps. */
  const plannedVersion = existing !== null ? latest.version : latest.version + 1;
  // Refused before any write: neither a master version nor a row change.
  if (rebuildAt(target, plannedVersion, args) === null) return { ok: false, message: CHANGED_MASTER, masterInserted: false };

  // The version actually pinned: the planned one unless the database assigned another.
  let version = plannedVersion;
  // Whether this click created the master version.
  let masterInserted = false;
  // Only a skill the latest master lacks needs a new version.
  if (existing === null) {
    // Insert-only; the database assigns the version and the content hash.
    const stored = await storeMasterProfile(client, target);
    // Each refusal named: nothing has been written anywhere yet.
    if (stored.kind !== 'stored') return { ok: false, message: `could not add it to your master profile: ${storeRefusalMessage(stored)}.`, masterInserted: false };
    // The real number, which a concurrent save could have pushed past latest+1.
    version = stored.version;
    // From here on a master version exists.
    masterInserted = true;
  }

  // The proof again at the real version (pure; only the label differs from the planned one).
  const rebuilt = rebuildAt(target, version, args);
  // Refused after the insert: the version stays (immutable), the row is untouched.
  if (rebuilt === null) return { ok: false, message: CHANGED_MASTER, masterInserted };
  // The existing add, against the re-pinned resume: the skill is built field for field from the master node.
  // The line was already judged above, against this same resume; 'allow' keeps addSkill from judging it twice.
  const added = addSkill({ ...args.current, master_version: version }, target, skillRef, 'allow');
  // e.g. already on the resume; said in addSkill's own words.
  if (!added.ok) return { ok: false, message: added.reason, masterInserted };
  /* One page (2026-11-07): the attested resume is fitted BEFORE the write, and the fitted one is
     stored. Skills are never trimmed, so the new skill stays; something else may be cut, and is
     announced. Floors that overflow refuse here, after the master version (if made) was inserted:
     that version stays (immutable), and the row is untouched, like every other post-insert refusal. */
  // Content rules against the stored resume and the NEW pin's master (the one the row will be pinned to).
  const fitted = fitEditToOnePage(added.resume, args.jdKeywords, { previous: args.current, master: target });
  // Refused before the write, in the check's own words.
  if (!fitted.ok) return { ok: false, message: fitted.reason, masterInserted };

  // One write: the resume with the skill, and all three pins, guarded by status and stamp.
  const saved = await saveTailoredEdit(client, {
    // The row being written.
    applicationId: args.applicationId,
    // The resume with the attested skill, already labelled with the new version, fitted on one page.
    resume: fitted.resume,
    // What is stored now, for the unchanged R0 check (relabelled to the new pin inside the save).
    previous: args.current,
    // The tailor's version at the NEW pin, proven claim-for-claim identical above.
    original: rebuilt.original,
    // The new pin's master, the only source the added skill may come from.
    master: target,
    // Optimistic concurrency: refused if another tab changed the row.
    expectedUpdatedAt: args.expectedUpdatedAt,
    // The event names the master skill and that the operator vouched for it.
    event: { kind: 'resume_attest_skill', ref: skillRef, before: null, after: name, source: args.source, pageFitTrimmed: fitted.trimmed },
    // All three pins move in this same statement.
    repin: { version, tailorRefs: rebuilt.refs },
  });
  // Refused or unknown: the page shows what is stored; the master version, if made, stays.
  if (!saved.ok) return { ok: false, message: saved.message, masterInserted, ...(saved.stored ? { stored: saved.stored } : {}) };
  // Everything the page needs to redraw against the new pin.
  return {
    // Landed.
    ok: true,
    // The resume as stored (fitted).
    resume: fitted.resume,
    // What the one-page fit cut, and an allowed wrap, in words for the page to show; null when neither happened.
    notice: [fitted.notice, wrapNotice].filter((line): line is string => line !== null).join(' ') || null,
    // The pin's master, which the page swaps into the row's source.
    master: target,
    // The pin's original, so "edited" keeps being derived correctly.
    original: rebuilt.original,
    // The tailor's record as stored, for any later re-pin.
    tailorRefs: rebuilt.refs,
    // The skill for Undo.
    skillRef,
    // The stamp the next edit must present.
    updatedAt: saved.updatedAt,
    // True only when this click inserted the master version.
    masterInserted,
    // So the page can say when only the history note is missing.
    eventRecorded: saved.eventRecorded,
  };
}
